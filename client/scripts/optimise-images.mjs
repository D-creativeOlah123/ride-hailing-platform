// Downloads the landing-page photos listed in landing-images.json and writes
// optimised WebP files to public/landing/:  <file>.webp (large) and <file>-sm.webp (small).
// Originals are cached in .image-cache/ (git-ignored) so re-runs are fast.
//
// Usage: npm run images            (skips files that already exist)
//        npm run images -- --force (re-encode everything)
import { readFile, writeFile, mkdir, access } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const outDir = path.join(root, 'public', 'landing')
const cacheDir = path.join(root, '.image-cache')
const force = process.argv.includes('--force')

const SIZES = {
  hero: { large: 1920, small: 960 },
  card: { large: 1280, small: 640 },
  portrait: { large: 480, small: 240, square: true },
}
const QUALITY = 80

const exists = (p) => access(p).then(() => true, () => false)

async function original(img) {
  const file = path.join(cacheDir, `${img.file}.jpg`)
  if (await exists(file)) return file
  const res = await fetch(`${img.src}?w=2400&q=85&fm=jpg`)
  if (!res.ok) throw new Error(`${img.file}: download failed (${res.status})`)
  await writeFile(file, Buffer.from(await res.arrayBuffer()))
  return file
}

async function encode(input, output, width, square) {
  const pipeline = sharp(input).rotate()
  if (square) pipeline.resize(width, width, { fit: 'cover', position: sharp.strategy.attention })
  else pipeline.resize({ width, withoutEnlargement: true })
  const info = await pipeline.webp({ quality: QUALITY, effort: 5 }).toFile(output)
  return info
}

const { images } = JSON.parse(await readFile(path.join(root, 'scripts', 'landing-images.json'), 'utf8'))
await mkdir(outDir, { recursive: true })
await mkdir(cacheDir, { recursive: true })

let total = 0
for (const img of images) {
  const size = SIZES[img.kind]
  const large = path.join(outDir, `${img.file}.webp`)
  const small = path.join(outDir, `${img.file}-sm.webp`)
  if (!force && (await exists(large)) && (await exists(small))) {
    console.log(`skip  ${img.file}`)
    continue
  }
  const src = await original(img)
  const a = await encode(src, large, size.large, size.square)
  const b = await encode(src, small, size.small, size.square)
  total += a.size + b.size
  console.log(`done  ${img.file.padEnd(30)} ${a.width}x${a.height} ${(a.size / 1024).toFixed(0)} KB  |  ${b.width}w ${(b.size / 1024).toFixed(0)} KB`)
}
console.log(`\nWrote ${(total / 1024).toFixed(0)} KB of WebP to public/landing/`)

// Record final dimensions so <img> tags get explicit width/height (no layout shift).
const meta = {}
for (const img of images) {
  const l = await sharp(path.join(outDir, `${img.file}.webp`)).metadata()
  const s = await sharp(path.join(outDir, `${img.file}-sm.webp`)).metadata()
  meta[img.file] = { w: l.width, h: l.height, smW: s.width, by: img.by, page: img.page }
}
const metaFile = path.join(root, 'src', 'components', 'landing', 'images.generated.js')
await mkdir(path.dirname(metaFile), { recursive: true })
await writeFile(metaFile,
  '// Generated by scripts/optimise-images.mjs — do not edit by hand.\n' +
  `export default ${JSON.stringify(meta, null, 2)}\n`)
console.log('Wrote src/components/landing/images.generated.js')
